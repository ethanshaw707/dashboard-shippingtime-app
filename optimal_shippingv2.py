def load_dotenv(path: Path) -> None:
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip("\"'")
        if key and key not in os.environ:
            os.environ[key] = value


def env_api_key() -> str:
    load_dotenv(Path(".env"))
    key = os.getenv(API_KEY_ENV, "").strip()
    if not key:
        raise RuntimeError(f"Missing env var {API_KEY_ENV}. Put it in .env")
    return key


def make_session(api_key: str) -> requests.Session:
    s = requests.Session()
    s.headers.update(
        {
            "api-key": api_key,
            "Content-Type": "application/json",
            "User-Agent": "optimal-shipping/regionals",
        }
    )
    return s


def http_json(session: requests.Session, method: str, url: str, payload: Optional[dict] = None, timeout: int = 60) -> dict:
    for attempt in range(3):
        try:
            resp = session.request(method, url, json=payload, timeout=timeout)
            if resp.status_code >= 500:
                raise RuntimeError(f"Server error {resp.status_code}: {resp.text[:300]}")
            resp.raise_for_status()
            return resp.json()
        except Exception:
            if attempt == 2:
                raise
            time.sleep(0.8 * (attempt + 1))
    raise RuntimeError("Unreachable")


def list_carriers(session: requests.Session) -> List[dict]:
    data = http_json(session, "GET", f"{SHIPSTATION_BASE_URL}/carriers")
    return data.get("carriers", [])


