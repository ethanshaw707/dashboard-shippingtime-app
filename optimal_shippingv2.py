def normalize_rate_block(data: dict) -> dict:
    return data.get("rate_response") or data


def safe_amount(x: Any) -> float:
    if isinstance(x, dict) and "amount" in x:
        try:
            return float(x["amount"])
        except Exception:
            return 0.0
    try:
        return float(x)
    except Exception:
        return 0.0


def ui_like_amount(rate: Dict[str, Any]) -> float:
    return round(safe_amount(rate.get("shipping_amount")), 2)


def find_service(rates: List[Dict[str, Any]], service_code: str) -> Optional[Dict[str, Any]]:
    for r in rates:
        if (r.get("service_code") or "") == service_code:
            return r
    return None


def write_csv(path: Path, rows: List[Dict[str, Any]]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main() -> int:
    api_key = env_api_key()
    session = make_session(api_key)
    carriers = list_carriers(session)
    carrier_ids = [c.get("carrier_id") for c in carriers if c.get("carrier_id")]

    if not carrier_ids:
        print("No carriers found.")
        return 2

    ship_date = date.today().isoformat()
    summary_csv = Path("shipping_summary_regionals_v22_3.csv")

    summary_rows: List[Dict[str, Any]] = []
    save_interval = 10

    for ship_from in SHIP_FROM_LOCATIONS:
        for ship_to in SHIP_TO_LOCATIONS:
            for pkg in PACKAGES:
                payload = build_rates_payload(
                    carrier_ids=carrier_ids,
                    ship_date=ship_date,
                    ship_from=ship_from,
                    ship_to=ship_to,
                    pkg=pkg,
                )

                data = http_json(session, "POST", f"{SHIPSTATION_BASE_URL}/rates", payload=payload)

                print(f"{ship_from.city_locality} -> {ship_to.city_locality}, {ship_to.state_province} ({pkg.label})")
                rate_block = normalize_rate_block(data)
                rates = rate_block.get("rates") or []

                ups_ground = find_service(rates, "ups_ground")
                cost = ui_like_amount(ups_ground) if ups_ground else ""
                days = ups_ground.get("delivery_days") if ups_ground else ""
                service = (ups_ground.get("service_type") or ups_ground.get("service_code")) if ups_ground else ""
                if ups_ground:
                    days_label = f"{days} days" if days != "" else "N/A"
                    print(f"  UPS Ground: ${cost:.2f} | {days_label}")
                else:
                    print("  UPS Ground: not available")
                print()

                summary_rows.append(
                    {
                        "FromAddress": ship_from.city_locality,
                        "ToCity": ship_to.city_locality,
                        "ToState": ship_to.state_province,
                        "PackageSize": pkg.label,
                        "Cost": cost,
                        "ShippingTimeDays": days,
                        "Service": service,
                    }
                )

                if len(summary_rows) % save_interval == 0:
                    write_csv(summary_csv, summary_rows)

    write_csv(summary_csv, summary_rows)
    return 0


